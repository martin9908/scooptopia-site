// Generates docs/supabase-seed.sql from data/site-content.json (the default
// Scooptopia template). Run with: pnpm seed:gen
//
// Keeping the seed generated rather than hand-written means it never drifts
// from the template data the app ships with.

import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "data", "site-content.json");
const outputPath = path.join(root, "docs", "supabase-seed.sql");

const raw = await readFile(sourcePath, "utf8");
const content = JSON.parse(raw); // validate it parses
const pretty = JSON.stringify(content, null, 2);

// Escape single quotes for the SQL string literal (PostgreSQL doubles them).
const escaped = pretty.replace(/'/g, "''");

const sql = `-- Generated by scripts/generate-supabase-seed.mjs from data/site-content.json
-- Do not edit by hand. Run \`pnpm seed:gen\` to regenerate.
--
-- Populates the \`primary\` row of public.site_content with the default
-- Scooptopia template. Re-running resets that row back to the template,
-- overwriting any edits made through /admin.

insert into public.site_content (id, content)
values ('primary', '${escaped}'::jsonb)
on conflict (id) do update set content = excluded.content;
`;

await writeFile(outputPath, sql, "utf8");
console.log(`Wrote ${path.relative(root, outputPath)} (${escaped.length} chars of JSON).`);
